def set_run_font(run, size: int, bold: bool = False) -> None:
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = RGBColor(0, 0, 0)


def style_body_paragraph(paragraph, indent: bool = True, center: bool = False) -> None:
    fmt = paragraph.paragraph_format
    fmt.line_spacing = 1.5
    fmt.space_before = Pt(0)
    fmt.space_after = Pt(0)
    if indent:
        fmt.first_line_indent = Cm(0.74)
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER if center else WD_ALIGN_PARAGRAPH.JUSTIFY


def add_paragraph(doc: Document, text: str, size: int = 12, bold: bool = False, indent: bool = True, center: bool = False):
    p = doc.add_paragraph()
    style_body_paragraph(p, indent=indent, center=center)
    run = p.add_run(text)
    set_run_font(run, size=size, bold=bold)
    return p


def add_heading(doc: Document, text: str, level: int):
    size_map = {1: 16, 2: 14, 3: 12}
    p = doc.add_paragraph()
    style_body_paragraph(p, indent=False, center=False)
    run = p.add_run(text)
    set_run_font(run, size=size_map.get(level, 12), bold=True)
    return p


def add_toc(doc: Document) -> None:
    p = doc.add_paragraph()
    style_body_paragraph(p, indent=False, center=False)
    run = p.add_run()
    set_run_font(run, size=12, bold=False)

    fld_begin = OxmlElement("w:fldChar")
    fld_begin.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = r'TOC \o "1-3" \h \z \u'
    fld_separate = OxmlElement("w:fldChar")
    fld_separate.set(qn("w:fldCharType"), "separate")
    hint = OxmlElement("w:t")
    hint.text = "打开 Word 后如目录未自动显示，可右键目录选择“更新域”。"
    fld_end = OxmlElement("w:fldChar")
    fld_end.set(qn("w:fldCharType"), "end")

    run._r.append(fld_begin)
    run._r.append(instr)
    run._r.append(fld_separate)
    run._r.append(hint)
    run._r.append(fld_end)


def configure(doc: Document) -> None:
    section = doc.sections[0]
    section.top_margin = Cm(2.54)
    section.bottom_margin = Cm(2.54)
    section.left_margin = Cm(3.0)
    section.right_margin = Cm(2.5)

    normal = doc.styles["Normal"]
    normal.font.name = "Times New Roman"
    normal._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    normal.font.size = Pt(12)
    normal.font.color.rgb = RGBColor(0, 0, 0)


def build_document() -> Document:
    doc = Document()
    configure(doc)

    add_paragraph(doc, "江苏科技大学大学生创新创业训练计划项目", size=16, bold=True, indent=False, center=True)
    add_paragraph(doc, TITLE, size=20, bold=True, indent=False, center=True)
    doc.add_paragraph()
    add_paragraph(doc, "项目负责人：钱鑫", size=14, indent=False, center=True)
    add_paragraph(doc, "指导教师：王丽娟", size=14, indent=False, center=True)
    add_paragraph(doc, "项目类别：创新训练项目", size=14, indent=False, center=True)
    add_paragraph(doc, "形成时间：2026年3月", size=14, indent=False, center=True)

    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)

    for chapter_index, (chapter_title, sections) in enumerate(CHAPTERS):
        add_heading(doc, chapter_title, 1)
        if chapter_title == "目  录":
            add_toc(doc)
        else:
            for section_title, paragraphs in sections:
                if section_title:
                    add_heading(doc, section_title, 2)
                for text in paragraphs:
                    add_paragraph(doc, text, size=12, bold=False, indent=True, center=False)

        if chapter_index != len(CHAPTERS) - 1:
            doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)

    return doc


def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    doc = build_document()
    doc.save(DOCX_PATH)
    print(DOCX_PATH)


if __name__ == "__main__":
    main()
